export async function fetchLiveDharaniTeaProducts() {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 6000);
    const response = await fetch('https://api.codingboss.in/vandanmart/products/', {
      signal: controller.signal,
      headers: {
        'Accept': 'application/json'
      }
    });
    clearTimeout(timeoutId);

    if (!response.ok) {
      throw new Error(`API returned HTTP ${response.status}`);
    }

    const allProducts = await response.json();
    if (!Array.isArray(allProducts) || allProducts.length === 0) {
      return DHARANI_TEA_PRODUCTS_INITIAL;
    }

    return DHARANI_TEA_PRODUCTS_INITIAL.map((initial) => {
      const match = allProducts.find((p) => p.id === initial.dharaniId);
      if (match) {
        return {
          ...initial,
          price: match.price ? parseFloat(match.price).toFixed(2) : initial.price,
          image: match.image || initial.image,
          stock: match.stock !== undefined ? match.stock : 500,
        };
      }
      return initial;
    });
  } catch (err) {
    console.warn('Live Dharani Tea fetch note:', err.message);
    return DHARANI_TEA_PRODUCTS_INITIAL;
  }
}
